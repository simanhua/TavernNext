type Variables = Record<string, string | number>;

function interpolate(template: string, variables?: Variables): string {
  if (variables === undefined) return template;
  return template.replace(/\{\{(\w+)\}\}/g, (match, key: string) => String(variables[key] ?? match));
}

function initialLanguage(): Language {
  if (typeof window === 'undefined') return 'en';
  const saved = window.localStorage.getItem(STORAGE_KEY);
  if (saved === 'en' || saved === 'zh-CN') return saved;
  return window.navigator.language.toLowerCase().startsWith('zh') ? 'zh-CN' : 'en';
}

interface I18nValue {
  language: Language;
  setLanguage(language: Language): void;
  t(key: string, variables?: Variables): string;
}

const I18nContext = createContext<I18nValue | undefined>(undefined);

export function I18nProvider({ children }: { children: ReactNode }) {
  const [language, setLanguage] = useState<Language>(initialLanguage);
  useEffect(() => {
    window.localStorage.setItem(STORAGE_KEY, language);
    document.documentElement.lang = language;
  }, [language]);
  const value = useMemo<I18nValue>(() => ({
    language,
    setLanguage,
    t: (key, variables) => interpolate(language === 'zh-CN' ? (zhCN[key] ?? key) : key, variables),
  }), [language]);
  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n(): I18nValue {
  const value = useContext(I18nContext);
  if (value === undefined) throw new Error('useI18n must be used within I18nProvider');
  return value;
}
